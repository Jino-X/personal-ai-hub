"use client";

import type { FeedItem } from "@hub/shared";
import { ArrowUpRight, Sparkles } from "lucide-react";
import { useEffect } from "react";
import { Markdown } from "@/components/common/markdown";
import { ErrorState } from "@/components/common/states";
import { Dialog, DialogContent, DialogDescription, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { Skeleton } from "@/components/ui/skeleton";
import { useExplainItem } from "@/lib/api/hooks/intelligence";

/** On-demand deeper AI explanation (e.g. of technical changes in a release). */
export function ExplainDialog({ item, onClose }: { item: FeedItem | null; onClose: () => void }) {
  const explain = useExplainItem();
  const { mutate, reset } = explain;

  useEffect(() => {
    if (item) mutate(item.id);
    else reset();
  }, [item, mutate, reset]);

  return (
    <Dialog open={item !== null} onOpenChange={(o) => !o && onClose()}>
      <DialogContent className="max-h-[85vh] overflow-y-auto sm:max-w-2xl">
        <DialogHeader>
          <DialogTitle className="pr-6 leading-snug">{item?.title}</DialogTitle>
          <DialogDescription className="flex items-center gap-1.5">
            <Sparkles className="size-3 text-primary" /> AI explanation based only on the source text ·{" "}
            {item && (
              <a href={item.url} target="_blank" rel="noopener noreferrer" className="inline-flex items-center text-primary hover:underline">
                original source <ArrowUpRight className="size-3" />
              </a>
            )}
          </DialogDescription>
        </DialogHeader>
        {explain.isPending ? (
          <div className="space-y-2">
            <Skeleton className="h-4 w-full" />
            <Skeleton className="h-4 w-5/6" />
            <Skeleton className="h-4 w-4/6" />
            <p className="pt-2 text-xs text-muted-foreground">Your local model is reading the source…</p>
          </div>
        ) : explain.isError ? (
          <ErrorState error={explain.error} onRetry={() => item && mutate(item.id)} compact />
        ) : explain.data ? (
          <>
            <Markdown>{explain.data.explanation}</Markdown>
            <p className="text-[11px] text-muted-foreground">Generated by {explain.data.model}. Verify important details in the original source.</p>
          </>
        ) : null}
      </DialogContent>
    </Dialog>
  );
}
